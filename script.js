// ======================================================
// START GAME
// ======================================================

startButton.addEventListener(
    "click",
    startGame
);


playerNameInput.addEventListener(
    "keydown",
    function(event) {

        if (event.key === "Enter") {

            startGame();

        }

    }
);


function startGame() {

    const name =
        playerNameInput.value.trim();


    if (name === "") {

        alert("Please enter your streamer name.");

        return;

    }


    playerName =
        name;

    currentChallenge =
        null;

    completedChallenges =
        [];

    availableChallenges =
        [...challenges];


    displayName.textContent =
        playerName;


    completedCount.textContent =
        "0";


    completedList.innerHTML =
        "";


    challengeText.textContent =
        "Click the button to get your challenge.";


    challengeNumber.textContent =
        "Challenge 1";


    randomButton.classList.remove(
        "hidden"
    );


    completeButton.classList.add(
        "hidden"
    );


    setupScreen.classList.add(
        "hidden"
    );


    gameScreen.classList.remove(
        "hidden"
    );


    promoText.textContent =
        promoMessages[0];

}


// ======================================================
// GENERATE RANDOM CHALLENGE
// ======================================================

randomButton.addEventListener(
    "click",
    generateChallenge
);


function generateChallenge() {

    if (availableChallenges.length === 0) {

        availableChallenges =
            [...challenges];

    }


    const randomIndex =
        Math.floor(
            Math.random() *
            availableChallenges.length
        );


    currentChallenge =
        availableChallenges[randomIndex];


    availableChallenges.splice(
        randomIndex,
        1
    );


    challengeText.textContent =
        currentChallenge;


    challengeNumber.textContent =
        `Challenge ${completedChallenges.length + 1}`;


    randomButton.classList.add(
        "hidden"
    );


    completeButton.classList.remove(
        "hidden"
    );

}


// ======================================================
// COMPLETE CHALLENGE
// ======================================================

completeButton.addEventListener(
    "click",
    completeChallenge
);


function completeChallenge() {

    if (!currentChallenge) {

        return;

    }


    completedChallenges.push(
        currentChallenge
    );


    const item =
        document.createElement("div");


    item.className =
        "completed-item";


    item.textContent =
        `✓ ${completedChallenges.length}. ${currentChallenge}`;


    completedList.prepend(
        item
    );


    completedCount.textContent =
        completedChallenges.length;


    currentChallenge =
        null;


    challengeText.textContent =
        "Challenge completed!";


    challengeNumber.textContent =
        `Challenge ${completedChallenges.length + 1}`;


    randomButton.classList.remove(
        "hidden"
    );


    completeButton.classList.add(
        "hidden"
    );


    updatePromotion();


    // PLAY RANDOM MEME
    playRandomMeme();

}


// ======================================================
// RANDOM MEME
// ======================================================

function playRandomMeme() {

    if (memes.length === 0) {

        return;

    }


    const randomIndex =
        Math.floor(
            Math.random() *
            memes.length
        );


    const selectedMeme =
        memes[randomIndex];


    memeVideo.src =
        selectedMeme;


    memeOverlay.classList.remove(
        "hidden"
    );


    // Try to autoplay

    const playPromise =
        memeVideo.play();


    if (playPromise !== undefined) {

        playPromise.catch(function() {

            // Browser blocked autoplay.
            // The video controls will still work.

            console.log(
                "Autoplay was blocked by the browser."
            );

        });

    }

}


// ======================================================
// MEME FINISHED
// ======================================================

memeVideo.addEventListener(
    "ended",
    closeMeme
);


// ======================================================
// CLOSE MEME
// ======================================================

closeMemeButton.addEventListener(
    "click",
    closeMeme
);


skipMemeButton.addEventListener(
    "click",
    closeMeme
);


function closeMeme() {

    memeVideo.pause();

    memeVideo.currentTime =
        0;

    memeVideo.removeAttribute(
        "src"
    );

    memeVideo.load();


    memeOverlay.classList.add(
        "hidden"
    );

}


// ======================================================
// PROMOTIONAL MESSAGE
// ======================================================

function updatePromotion() {

    const index =
        Math.floor(
            completedChallenges.length / 2
        ) % promoMessages.length;


    promoText.textContent =
        promoMessages[index];

}


